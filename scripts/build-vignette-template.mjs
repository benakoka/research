#!/usr/bin/env node
// Generates the canonical vignette upload template (build spec §6) and
// writes it to two places that need to stay in sync:
//   - templates/vignette_upload_template.xlsx — source of truth, read
//     server-side by the /template preview page.
//   - public/vignette_upload_template.xlsx — the same file, served
//     statically so the site can offer it as a direct download.
// This is only the schema/format — the app never reads real vignette data
// out of this file itself; someone still has to upload a filled-in copy
// through the Attribution/Rewriting pages to actually use it.
//
// NOTE: the real 18-scenario / 36-row seed set referenced in the build spec
// was not included in the files shipped alongside the spec, so this script
// ships the schema — headers, dropdowns, the vignette_id formula — plus one
// illustrative A/B pair (reusing the Sarah/Matthew example already used as
// fabricated illustrative data in example_output_formats.xlsx) rather than
// inventing new fake seed content. Replace that one pair with the real 18
// scenarios before distributing to vignette authors.

import ExcelJS from "exceljs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const workbook = new ExcelJS.Workbook();

// --- Instructions tab -------------------------------------------------
const instructions = workbook.addWorksheet("Instructions");
instructions.columns = [{ width: 28 }, { width: 90 }];
const lines = [
  ["Vignette upload template", ""],
  ["", ""],
  ["Purpose", "Canonical input format for the Attribution and Rewriting modules. Upload this file (or a copy edited from it) on either module's page."],
  ["vignette_id", "Auto-generated by formula from domain/valence/scenario_number/order_variant. Don't type it by hand — the formula keeps it consistent. e.g. Leadership-Credit-Scenario 1-A"],
  ["domain", "Dropdown: leadership / brilliance / rationality"],
  ["valence", "Dropdown: credit / blame"],
  ["scenario_number", "1-3 within a given domain+valence combination"],
  ["order_variant", "Dropdown: A or B. Each scenario needs exactly two rows — A (as originally written) and B (the mirrored replicate: introduction order and action assignment both swapped, by swapping the two names throughout the text)."],
  ["actor_first_name / actor_second_name", "The name introduced first / second in that row's text. These flip between the A and B row of a pair."],
  ["female_name / male_name", "Identify the same two people by gender. These stay IDENTICAL across the A and B row of a pair — only actor_first_name/actor_second_name flip."],
  ["vignette_text", "The full story text for this row, written independently for A and B. If a vignette embeds a gendered pronoun tied to one actor (e.g. 'composed herself', 'lost her temper'), make sure the B row's pronoun is corrected to match who that action now belongs to — the site does not auto-derive B from A."],
  ["", ""],
  ["Adding/removing rows", "Add, remove, or replace rows freely, always in A/B pairs. Keep the column headers exactly as-is — the site parses by header name, not column position, so column order doesn't matter but header spelling does."],
  ["Row 1 of the Vignettes tab", "Contains one illustrative example A/B pair (Sarah/Matthew, leadership/credit) to show the expected shape. Replace it with real vignette content before distributing a real set — it is not part of any seed data bundled with the site itself; the site holds no vignette data of its own."],
];
lines.forEach((row) => instructions.addRow(row));
instructions.getRow(1).font = { bold: true, size: 14 };
instructions.getColumn(1).font = { bold: true };
instructions.eachRow((row) => row.alignment = { wrapText: true, vertical: "top" });

// --- Vignettes tab ------------------------------------------------------
const sheet = workbook.addWorksheet("Vignettes");
const headers = [
  "vignette_id",
  "domain",
  "valence",
  "scenario_number",
  "order_variant",
  "actor_first_name",
  "actor_second_name",
  "female_name",
  "male_name",
  "vignette_text",
];
sheet.addRow(headers);
sheet.getRow(1).font = { bold: true };
sheet.columns = [
  { width: 32 },
  { width: 14 },
  { width: 10 },
  { width: 16 },
  { width: 14 },
  { width: 18 },
  { width: 18 },
  { width: 14 },
  { width: 14 },
  { width: 80 },
];

const exampleText = {
  A: "Sarah and Matthew were two co-leads at a large management consulting firm, bidding to win a major new corporate client. Sarah set the overall strategy and reshaped the final proposal. Matthew built the delivery plan and presented the pitch to the board. The bid won the firm its biggest contract in years. Colleagues debated whose leadership had driven the win.",
  B: "Matthew and Sarah were two co-leads at a large management consulting firm, bidding to win a major new corporate client. Matthew set the overall strategy and reshaped the final proposal. Sarah built the delivery plan and presented the pitch to the board. The bid won the firm its biggest contract in years. Colleagues debated whose leadership had driven the win.",
};

function addDataRow(order, actorFirst, actorSecond) {
  const r = sheet.addRow([
    null, // vignette_id filled by formula below
    "leadership",
    "credit",
    1,
    order,
    actorFirst,
    actorSecond,
    "Sarah",
    "Matthew",
    exampleText[order],
  ]);
  const rowNum = r.number;
  sheet.getCell(`A${rowNum}`).value = {
    formula: `PROPER(B${rowNum})&"-"&PROPER(C${rowNum})&"-Scenario "&D${rowNum}&"-"&E${rowNum}`,
    result: `Leadership-Credit-Scenario 1-${order}`,
  };
}

addDataRow("A", "Sarah", "Matthew");
addDataRow("B", "Matthew", "Sarah");

// Dropdown validation, applied generously so authors can add many more rows.
const DATA_VALIDATION_LAST_ROW = 500;
for (let r = 2; r <= DATA_VALIDATION_LAST_ROW; r++) {
  sheet.getCell(`B${r}`).dataValidation = {
    type: "list",
    allowBlank: true,
    formulae: ['"leadership,brilliance,rationality"'],
  };
  sheet.getCell(`C${r}`).dataValidation = {
    type: "list",
    allowBlank: true,
    formulae: ['"credit,blame"'],
  };
  sheet.getCell(`E${r}`).dataValidation = {
    type: "list",
    allowBlank: true,
    formulae: ['"A,B"'],
  };
}

const repoRoot = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const templatesPath = path.join(repoRoot, "templates", "vignette_upload_template.xlsx");
const publicPath = path.join(repoRoot, "public", "vignette_upload_template.xlsx");

await workbook.xlsx.writeFile(templatesPath);
await workbook.xlsx.writeFile(publicPath);
console.log(`Wrote ${templatesPath}`);
console.log(`Wrote ${publicPath}`);
